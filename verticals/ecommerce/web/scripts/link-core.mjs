/**
 * The e-commerce web app is the core Softilo app plus its own screens. This script links in every
 * core screen as a one-line re-export (so core fixes flow through) and copies the brand assets.
 * Run it after core screens are added or removed:  pnpm --filter @softilo-ecommerce/web link-core
 */
import { copyFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(dirname(fileURLToPath(import.meta.url)));
const core = join(here, "..", "..", "..", "apps", "web");
const HEADER = "// Generated by scripts/link-core.mjs: a core Softilo screen. Do not edit; change apps/web instead.\n";

function* pages(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* pages(p);
    else if (name === "page.tsx") yield p;
  }
}

let n = 0;
for (const file of pages(join(core, "app"))) {
  const rel = relative(join(core, "app"), file);
  const target = join(here, "app", rel);
  if (existsSync(target) && !readFileSync(target, "utf8").startsWith(HEADER)) continue; // the edition overrides this screen
  mkdirSync(dirname(target), { recursive: true });
  const spec = `@/app/${rel.split(sep).join("/").replace(/\.tsx$/, "")}`;
  writeFileSync(target, `${HEADER}export { default } from "${spec}";\n`);
  n++;
}
for (const asset of ["icon.svg", "favicon.ico", "apple-icon.png"]) copyFileSync(join(core, "app", asset), join(here, "app", asset));
rmSync(join(here, "public"), { recursive: true, force: true });
cpSync(join(core, "public"), join(here, "public"), { recursive: true });
console.log(`Linked ${n} core screens and copied brand assets`);

