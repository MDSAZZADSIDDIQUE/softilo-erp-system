// Re-export every core screen into this edition, so the edition is one app: core screens plus
// the manufacturing section. Run after core adds or removes a page: `node scripts/link-core-pages.mjs`.
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const coreApp = join(here, "..", "..", "..", "..", "apps", "web", "app");
const editionApp = join(here, "..", "app");

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : f === "page.tsx" ? [p] : [];
  });
}

for (const page of walk(coreApp)) {
  const rel = relative(coreApp, page).split("\\").join("/");
  const out = join(editionApp, rel);
  mkdirSync(dirname(out), { recursive: true });
  // `@/` resolves to the core web app (see tsconfig paths).
  writeFileSync(out, `// Generated by scripts/link-core-pages.mjs: the core screen, unchanged.\nexport { default } from "@/app/${rel.replace(/\.tsx$/, "")}";\n`);
  console.log(rel);
}
